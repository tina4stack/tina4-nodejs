/**
 * Frond vs the competition -- template rendering throughput (Node.js).
 *
 * The gap this fills: benchmark_results.json measures only `json` and `list`, and
 * carbonBenchmarks.ts measures Frond's template category against ITSELF in four
 * languages. Neither has ever timed Frond against the engines it competes with.
 *
 * Two things this harness does that a naive template benchmark does not:
 *
 * 1. IT PROVES THE ENGINES DO THE SAME WORK. Every engine renders the same page and the
 *    output is compared before anything is timed. Whitespace around block tags
 *    legitimately differs between engines, so the comparison collapses whitespace runs --
 *    but raw byte lengths are printed too, so a suspicious difference stays visible
 *    instead of being normalised away. A mismatch ABORTS. Timing engines that emit
 *    different HTML is the most common way a template benchmark lies.
 *
 * 2. IT MEASURES STEADY STATE, NOT COMPILATION. Each engine's template is compiled ONCE
 *    outside the clock, then rendered repeatedly, which is what a real app does per
 *    request. EJS compiles to a JS function and Nunjucks to a token program; doing
 *    either inside the loop would be a strawman, not a benchmark.
 *
 * Fairness rule: each engine uses ITS OWN idiomatic construct rather than being forced
 * into Frond's syntax. Nunjucks has no number_format filter, so it calls toFixed(2)
 * directly. The equivalence gate is what proves the comparison is honest -- not
 * identical template bytes.
 *
 * Competitor libraries live in this directory's package.json and its own node_modules,
 * never the framework's. Run: npm install && npx tsx benchmarks/benchTemplates.ts
 */

import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import ejs from "ejs";
import nunjucks from "nunjucks";

import { Frond } from "@tina4/frond";

/** Timed runs continue until this much wall-clock has elapsed. */
const MIN_SECONDS = 0.25;

/** ...but never fewer than this many iterations, however fast the engine. */
const MIN_ITERATIONS = 200;

/** 20 rows is a realistic list page, not a microbenchmark of one hole. */
function pageData() {
  return {
    title: "Benchmark Page",
    heading: "Product List",
    items: Array.from({ length: 20 }, (_, i) => ({
      name: `Product ${i}`,
      price: i * 9.99,
    })),
    show_footer: true,
    footer_text: "Generated by Tina4 Frond for the template throughput comparison.",
  };
}

/**
 * Collapse whitespace runs so block-tag indentation differences between engines do not
 * register as output differences. Everything else must match exactly.
 */
function normalise(html: string): string {
  return html.split(/\s+/).filter(Boolean).join(" ");
}

interface Measurement {
  p50_ops_sec: number;
  mean_ops_sec: number;
  iterations: number;
  batches: number;
}

/**
 * Time a render function: p50 and mean ops/sec.
 *
 * Batched for the same reason the carbon suite batches -- a render is fast enough that
 * two hrtime reads are a measurable fraction of the work, and a mean alone hides a fat
 * tail. Setup is outside the clock; only the render is timed.
 */
function measure(render: () => string): Measurement {
  // Warm-up is a LOOP and runs twice: one pass still pays cold costs (module init,
  // lazily-built caches, first compile, and in V8 the un-optimised first passes before
  // the JIT tiers up), and reading a single cold op collapses the batch size to 1,
  // defeating the amortisation.
  const CALIBRATION_OPS = 64;
  let one = 1e-9;
  for (let pass = 0; pass < 2; pass++) {
    const t0 = process.hrtime.bigint();
    for (let i = 0; i < CALIBRATION_OPS; i++) render();
    one = Math.max(Number(process.hrtime.bigint() - t0) / 1e9 / CALIBRATION_OPS, 1e-9);
  }

  const batch = Math.min(Math.max(Math.floor(5e-5 / one), 1), 10_000);

  const batches: number[] = [];
  let iterations = 0;
  const start = process.hrtime.bigint();
  for (;;) {
    const b0 = process.hrtime.bigint();
    for (let i = 0; i < batch; i++) render();
    batches.push(Number(process.hrtime.bigint() - b0) / 1e9 / batch);
    iterations += batch;
    const elapsed = Number(process.hrtime.bigint() - start) / 1e9;
    if (elapsed >= MIN_SECONDS && iterations >= MIN_ITERATIONS) break;
  }

  batches.sort((a, b) => a - b);
  const mid = Math.floor(batches.length / 2);
  const p50 = batches.length % 2 ? batches[mid] : (batches[mid - 1] + batches[mid]) / 2;
  const mean = batches.reduce((a, b) => a + b, 0) / batches.length;

  return {
    p50_ops_sec: p50 > 0 ? 1 / p50 : 0,
    mean_ops_sec: mean > 0 ? 1 / mean : 0,
    iterations,
    batches: batches.length,
  };
}

const FROND_SOURCE = `<!DOCTYPE html>
<html>
<head><title>{{ title }}</title></head>
<body>
<h1>{{ heading }}</h1>
<ul>
{% for item in items %}
<li class="{{ loop.index is even ? 'even' : 'odd' }}">{{ loop.index }}. {{ item.name|upper }} - \${{ item.price|number_format(2) }}</li>
{% endfor %}
</ul>
{% if show_footer %}
<footer>{{ footer_text }}</footer>
{% endif %}
</body>
</html>`;

// Nunjucks: same {{ }} / {% %} family (it is the Twig-alike for JS), but its own
// idioms -- an inline if-expression, and toFixed(2) instead of number_format.
const NUNJUCKS_SOURCE = `<!DOCTYPE html>
<html>
<head><title>{{ title }}</title></head>
<body>
<h1>{{ heading }}</h1>
<ul>
{% for item in items %}
<li class="{{ "even" if loop.index % 2 == 0 else "odd" }}">{{ loop.index }}. {{ item.name|upper }} - \${{ item.price.toFixed(2) }}</li>
{% endfor %}
</ul>
{% if show_footer %}
<footer>{{ footer_text }}</footer>
{% endif %}
</body>
</html>`;

const EJS_SOURCE = `<!DOCTYPE html>
<html>
<head><title><%= title %></title></head>
<body>
<h1><%= heading %></h1>
<ul>
<% items.forEach(function (item, idx) { %>
<li class="<%= (idx + 1) % 2 === 0 ? 'even' : 'odd' %>"><%= idx + 1 %>. <%= item.name.toUpperCase() %> - $<%= item.price.toFixed(2) %></li>
<% }); %>
</ul>
<% if (show_footer) { %>
<footer><%= footer_text %></footer>
<% } %>
</body>
</html>`;

const tmp = mkdtempSync(join(tmpdir(), "tina4_tpl_bench_"));
writeFileSync(join(tmp, "page.twig"), FROND_SOURCE);

const data = pageData();
const engines: Record<string, () => string> = {};

// --- Frond (Tina4, zero dependencies) --------------------------------------------
const frond = new Frond(tmp);
engines["Frond (Tina4)"] = () => frond.render("page.twig", data);

// --- Nunjucks (Mozilla; the Twig-alike for JS) -------------------------------------
// Compiled to a template object ONCE, outside the clock, with the filesystem loader
// disabled so nothing re-reads per render.
const nunjucksEnv = new nunjucks.Environment(null, { autoescape: true });
const nunjucksTemplate = nunjucks.compile(NUNJUCKS_SOURCE, nunjucksEnv);
engines["Nunjucks"] = () => nunjucksTemplate.render(data);

// --- EJS ----------------------------------------------------------------------------
// ejs.compile returns a real JS function; compiling per render would be a strawman.
const ejsTemplate = ejs.compile(EJS_SOURCE);
engines["EJS"] = () => ejsTemplate(data);

console.log(`\nTina4 Frond vs the competition -- template rendering (Node ${process.version})\n`);
console.log("  Output equivalence gate");
console.log("  " + "-".repeat(72));

const rendered: Record<string, string> = {};
for (const [name, fn] of Object.entries(engines)) rendered[name] = fn();

let reference: string | null = null;
let referenceName = "";
let mismatch = false;
for (const [name, html] of Object.entries(rendered)) {
  const norm = normalise(html);
  if (reference === null) {
    reference = norm;
    referenceName = name;
    console.log(`    ${name.padEnd(22)} ${String(html.length).padStart(6)} bytes raw  (reference)`);
    continue;
  }
  const same = norm === reference;
  console.log(
    `    ${name.padEnd(22)} ${String(html.length).padStart(6)} bytes raw  ${same ? "IDENTICAL" : "MISMATCH"}`,
  );
  if (!same) {
    mismatch = true;
    // Show where they diverge. A silent normalise-and-move-on is how a benchmark ends
    // up comparing engines that render different pages.
    const len = Math.min(norm.length, reference.length);
    let at = len;
    for (let i = 0; i < len; i++) {
      if (norm[i] !== reference[i]) { at = i; break; }
    }
    console.log(`      first difference at char ${at}:`);
    console.log(`        ${referenceName}: ...${reference.slice(Math.max(0, at - 40), at + 50)}...`);
    console.log(`        ${name}: ...${norm.slice(Math.max(0, at - 40), at + 50)}...`);
  }
}

if (mismatch) {
  console.log("\n  ABORTED: the engines do not render the same page, so any timing below");
  console.log("  would be comparing different work. Fix the templates first.\n");
  rmSync(tmp, { recursive: true, force: true });
  process.exit(1);
}

console.log("\n  All engines render the same page. Timing is meaningful.\n");

// Report Frond's configuration so the number cannot be dismissed as "you benchmarked
// the wrong path". Node's Frond caches tokens but has NO AOT compile-to-closure layer --
// PHP (FrondCompiler) and Python (frond/compiler.py) both do. That asymmetry is a real
// parity gap and the leading explanation for any gap below.
const debugMode = (process.env.TINA4_DEBUG || "").toLowerCase() === "true";
const frondAny = frond as unknown as Record<string, unknown>;
const hasAot = "compiledFn" in frondAny ? "present" : "NOT IMPLEMENTED in Node";
console.log("  Frond configuration (so the number cannot be dismissed)");
console.log("  " + "-".repeat(72));
console.log("    Token cache                    active (production path)");
console.log(`    AOT compile-to-closure layer   ${hasAot} -- PHP and Python have one`);
console.log(
  `    TINA4_DEBUG                    ${debugMode ? "true (dev: re-reads + re-tokenizes)" : "not true (production)"}`,
);
console.log();

console.log(
  `  ${"Engine".padEnd(22)} ${"p50 ops/sec".padStart(13)} ${"mean ops/sec".padStart(13)}   samples`,
);
console.log("  " + "-".repeat(72));

const results: Record<string, Measurement> = {};
for (const [name, fn] of Object.entries(engines)) {
  const m = measure(fn);
  results[name] = m;
  console.log(
    `  ${name.padEnd(22)} ${Math.round(m.p50_ops_sec).toLocaleString("en-US").padStart(13)}` +
      ` ${Math.round(m.mean_ops_sec).toLocaleString("en-US").padStart(13)}` +
      `   ${m.iterations.toLocaleString("en-US")}x${m.batches}`,
  );
}

const frondP50 = results["Frond (Tina4)"].p50_ops_sec;
console.log("\n  Relative to Frond (p50):");
for (const [name, m] of Object.entries(results)) {
  if (name === "Frond (Tina4)") continue;
  const ratio = m.p50_ops_sec > 0 ? frondP50 / m.p50_ops_sec : Infinity;
  console.log(
    `    Frond is ${(ratio >= 1 ? ratio : 1 / ratio).toFixed(2)}x ${ratio >= 1 ? "faster" : "SLOWER"} than ${name}`,
  );
}

writeFileSync(
  join(import.meta.dirname, "template_comparison.json"),
  JSON.stringify(
    {
      language: "nodejs",
      runtime: `Node ${process.version}`,
      page: { items: 20, engines: Object.keys(engines) },
      output_equivalence: "verified",
      aot_compile_layer: hasAot,
      results,
    },
    null,
    2,
  ) + "\n",
);

console.log("\n  Wrote template_comparison.json");
console.log("\n  Note: steady-state render only. Every engine's template is compiled ONCE");
console.log("  outside the clock, matching how an app serves a page. Cold-start compile");
console.log("  cost is a separate question and is NOT measured here.\n");

rmSync(tmp, { recursive: true, force: true });
